"""Comprehensive tests for Authentication, Authorization, Tenant Isolation, and Dynamic Permissions.

Verifies tenant boundaries through:
- Unauthorized source IDs (without suspicious wording)
- Unauthorized conversation IDs (without suspicious wording)
- Unauthorized answer IDs during retrieval
- Unauthorized clarification choice tampering
- Filter tampering targeting tenant isolation columns
- Dynamic permission verification during execution and retrieval
"""
import pytest
from talk2data.domain.models import TurnStatus
from talk2data.security.auth import AuthorizationError
from talk2data.intent.schema import StructuredIntent, AnalysisFamily


def test_tenant_isolation_database_queries(test_setup):
    """Ensure tenant A only sees tenant A data, and tenant B only sees tenant B data."""
    manager = test_setup["manager"]
    actor_a = test_setup["actor_a"]
    actor_b = test_setup["actor_b"]
    source_id = test_setup["source_id"]

    # Tenant A query for 2024 total sales (no suspicious words)
    turn_a, answer_a = manager.submit_turn(
        actor=actor_a,
        conversation_id="conv_a_clean_1",
        source_id=source_id,
        question="What was total sales in 2024?",
        proposed_llm_json='{"measure": "sales_revenue", "family": "TOTAL", "current_period": "2024"}',
    )
    assert turn_a.status == TurnStatus.ANSWERED
    assert answer_a is not None
    # Tenant A: 50,000 + 70,000 + 30,000 = 150,000.00
    assert "150,000.00" in answer_a.kpi_cards[0].value

    # Tenant B query for 2024 total sales (no suspicious words)
    turn_b, answer_b = manager.submit_turn(
        actor=actor_b,
        conversation_id="conv_b_clean_1",
        source_id=source_id,
        question="What was total sales in 2024?",
        proposed_llm_json='{"measure": "sales_revenue", "family": "TOTAL", "current_period": "2024"}',
    )
    assert turn_b.status == TurnStatus.ANSWERED
    assert answer_b is not None
    # Tenant B has 999,999.00
    assert "999,999.00" in answer_b.kpi_cards[0].value


