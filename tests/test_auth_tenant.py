def test_dynamic_permission_revocation_during_retrieval(test_setup):
    """Answer retrieval must fail if actor permissions to the source are revoked after execution."""
    manager = test_setup["manager"]
    actor_a = test_setup["actor_a"]
    source_id = test_setup["source_id"]
    security = test_setup["security"]

    turn, answer = manager.submit_turn(
        actor=actor_a,
        conversation_id="conv_dyn_revoc_1",
        source_id=source_id,
        question="What was total sales in 2024?",
        proposed_llm_json='{"measure": "sales_revenue", "family": "TOTAL", "current_period": "2024"}',
    )
    assert turn.status == TurnStatus.ANSWERED
    assert answer is not None

    # Revoke access to source_id for tenant_a
    security.revoke_tenant_source(actor_a.tenant_id, source_id)

    # Actor A attempts to retrieve the previously generated answer
    with pytest.raises(AuthorizationError):
        manager.get_answer(actor=actor_a, turn_id=turn.turn_id)

    # Re-grant for subsequent tests
    security.register_tenant_source(actor_a.tenant_id, source_id)


def test_dynamic_permission_revocation_before_execution(test_setup):
    """If permission is revoked while awaiting clarification, resuming execution is blocked."""
    manager = test_setup["manager"]
    actor_a = test_setup["actor_a"]
    source_id = test_setup["source_id"]
    security = test_setup["security"]

    turn, _ = manager.submit_turn(
        actor=actor_a,
        conversation_id="conv_dyn_exec_1",
        source_id=source_id,
        question="Compare 2024 with 2023.",
        proposed_llm_json='{"family": "COMPARISON", "current_period": "2024", "comparison_period": "2023"}',
    )
    assert turn.status == TurnStatus.AWAITING_CLARIFICATION
    choice_id = turn.clarification_request.options[0].choice_id

    # Revoke access to source before user answers clarification
    security.revoke_tenant_source(actor_a.tenant_id, source_id)

    with pytest.raises(AuthorizationError):
        manager.submit_clarification_choice(
            actor=actor_a,
            turn_id=turn.turn_id,
            choice_id=choice_id,
        )

    # Re-grant
    security.register_tenant_source(actor_a.tenant_id, source_id)


