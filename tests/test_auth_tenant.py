def test_dimension_permission_revocation_during_retrieval(test_setup):
    """Answer retrieval must fail if actor permissions to a dimension are revoked after execution."""
    manager = test_setup["manager"]
    security = test_setup["security"]
    actor_director = test_setup["actor_director"]
    source_id = test_setup["source_id"]

    # Director queries sales by country with VIP segment dimension
    turn, answer = manager.submit_turn(
        actor=actor_director,
        conversation_id="conv_director_dim_perm",
        source_id=source_id,
        question="What was sales revenue by country in 2024?",
        proposed_llm_json='{"measure": "sales_revenue", "family": "TOTAL", "dimensions": ["country"], "current_period": "2024"}',
    )
    assert turn.status == TurnStatus.ANSWERED
    assert answer is not None

    # Now director queries a restricted dimension (vip_segment)
    turn_vip, answer_vip = manager.submit_turn(
        actor=actor_director,
        conversation_id="conv_director_vip_perm",
        source_id=source_id,
        question="What was sales revenue by VIP segment in 2024?",
        proposed_llm_json='{"measure": "sales_revenue", "family": "TOTAL", "dimensions": ["vip_segment"], "current_period": "2024"}',
    )
    assert turn_vip.status == TurnStatus.ANSWERED
    assert answer_vip is not None

    # Demote director to standard analyst without sales_director role or read:vip_segment permission
    demoted_actor = security.authenticate_actor(
        tenant_id="tenant_a",
        subject_id="user_director",
        roles=("analyst",),
        permissions=set(),
    )

    # Retrieval of VIP segment turn must fail with AuthorizationError
    with pytest.raises(AuthorizationError, match="Insufficient role permissions for dimension 'VIP Segment'"):
        manager.get_answer(actor=demoted_actor, turn_id=turn_vip.turn_id)


def test_correlated_child_subqueries_enforce_tenant_scope(test_setup):
    """Verify that compiled SQL for child semi-joins and allocation includes tenant scope."""
    manager = test_setup["manager"]
    catalogs = test_setup["catalogs"]
    compiler = manager.compiler
    pin = catalogs.pin("tenant_a", "finance_dw")
    cat = catalogs.get_catalog("finance_dw", pin.release_id)

    # 1. Child semi-join filter
    intent_semi = StructuredIntent(
        measure="sales_revenue",
        family=AnalysisFamily.TOTAL,
        current_period="2024",
        filters=(
            from_import := __import__("talk2data.intent.schema", fromlist=["FilterSpec"]).FilterSpec(
                dimension="category", operator="=", values=("Hardware",)
            ),
        ),
    )
    plan_semi = manager.resolver.resolve(intent_semi, cat, pin, "turn_semi_test", "tenant_a")
    pkg_semi = compiler.compile(plan_semi)
    assert "order_items.tenant_id = :tenant_id" in pkg_semi.sql

    # 2. Allocation subquery
    intent_alloc = StructuredIntent(
        measure="sales_revenue_allocated",
        family=AnalysisFamily.TOTAL,
        dimensions=("category",),
        current_period="2022",
    )
    plan_alloc = manager.resolver.resolve(intent_alloc, cat, pin, "turn_alloc_test", "tenant_a")
    pkg_alloc = compiler.compile(plan_alloc)
    assert "order_items.tenant_id = :tenant_id" in pkg_alloc.sql

